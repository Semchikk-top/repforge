// Подключение к серверу по ссылке или QR: адрес пришёл извне, а подключение отправляет на него все данные
// о тренировках, поэтому перед этим всегда показываем адрес и спрашиваем.
export const confirmServer = (baseUrl: string): boolean =>
  confirm(`Подключиться к серверу ${baseUrl}? На него отправятся все данные о тренировках с этого устройства.`);
